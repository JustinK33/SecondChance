"""The frozen shared contract.

Every other module in the application builds against these types. Import them
from this package rather than from the submodules so that an internal
reorganisation does not ripple outward::

    from app.schemas import UserProfile, MatchStatus, ProgramMatch

Module map:

* ``common``      - primitives: money, URLs, UTC datetimes, slugs, pagination.
* ``enums``       - closed vocabularies shared with the database and frontend.
* ``profile``     - what we know about a person and how we learned it.
* ``eligibility`` - the typed rule DSL and its three-valued semantics.
* ``program``     - the curated catalog and its official sources.
* ``matching``    - a program paired with its deterministic verdict.
* ``plan``        - action plans and the shared-document dedup rule.
* ``workflow``    - the run polling contract.
* ``assistant``   - source-grounded chat.
* ``ai``          - model result envelopes and token/cost telemetry.
* ``contracts``   - ``Protocol`` seams between the layers.
"""

